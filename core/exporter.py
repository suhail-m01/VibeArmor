def compute_workspace_digest(root: Path) -> str:
    h = hashlib.sha256()
    for p in sorted(root.rglob("*")):
        if p.is_file() and ".vibearmor" not in p.parts and ".git" not in p.parts and "node_modules" not in p.parts:
            rel = str(p.relative_to(root)).replace("\\", "/")
            h.update(rel.encode("utf-8"))
            h.update(p.read_bytes())
    return h.hexdigest()[:16]


def compute_security_score(report: ScanAndHealReport) -> int:
    """Calculate 0-100 Wiz-style Security Posture Score based on active reachable findings."""
    active = (
        [f for f in report.findings_after if f.reachable and not f.requires_policy_spec]
        if report.mode == "auto_heal"
        else [f for f in report.findings_before if f.reachable and not f.requires_policy_spec]
    )
    if not active:
        # Deduct 4 points if human policy abstentions remain pending review, else 99
        return 96 if report.abstentions else 99

    penalty = 0
    for f in active:
        if f.severity.value == "CRITICAL":
            penalty += 22
        elif f.severity.value == "HIGH":
            penalty += 12
        elif f.severity.value == "MEDIUM":
            penalty += 6
        else:
            penalty += 2
    return max(8, 100 - penalty)


def build_git_patch(patches: List[PatchReport]) -> str:
    """Create a clean `git apply`-compatible unified diff across all verified fixes."""
    chunks: List[str] = [
        "# Generated by VibeArmor v2.0 — Closed-Loop Neuro-Symbolic DevSecOps Engine\n",
        f"# Timestamp (UTC): {dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}\n",
        "# Verification: Gate 1 (AST/SQL Compile) + Gate 2 (Cross-Layer Re-Scan) + Gate 3 (Sandbox Exploit Probe) PASSED\n\n",
    ]
    seen_files: Dict[str, tuple[str, str, bool]] = {}
    for p in patches:
        if p.status != RemediationStatus.FIXED_VERIFIED:
            continue
        for ed in p.edits:
            # Redact raw secrets inside .env.local if exported in a shareable git patch
            after_txt = ed.after_content
            target_path = ed.file_path
            if target_path == ".env.local":
                target_path = ".env.local.example"
                redacted_lines = []
                for ln in after_txt.splitlines():
                    if "=" in ln and not ln.lstrip().startswith("#"):
                        k, _ = ln.split("=", 1)
                        redacted_lines.append(f"{k}=<REPLACE_WITH_PRODUCTION_SECRET>")
                    else:
                        redacted_lines.append(ln)
                after_txt = "\n".join(redacted_lines) + "\n"

            if target_path not in seen_files:
                seen_files[target_path] = (ed.before_content, after_txt, ed.created_new)
            else:
                orig_before, _, orig_new = seen_files[target_path]
                seen_files[target_path] = (orig_before, after_txt, orig_new)

    for fpath, (before_c, after_c, is_new) in seen_files.items():
        is_added = bool(is_new and not before_c)
        from_hdr = "/dev/null" if is_added else f"a/{fpath}"
        to_hdr = f"b/{fpath}"
        diff_txt = "".join(
            difflib.unified_diff(
                before_c.splitlines(keepends=True),
                after_c.splitlines(keepends=True),
                fromfile=from_hdr,
                tofile=to_hdr,
                n=3,
            )
        )
        if diff_txt:
            chunks.append(f"diff --git a/{fpath} b/{fpath}\n")
            if is_added:
                chunks.append("new file mode 100644\n")
            chunks.append(diff_txt)
            if not diff_txt.endswith("\n"):
                chunks.append("\n")

    if len(chunks) <= 3:
        chunks.append("# No verified file modifications generated yet. Run Auto-Heal first.\n")
    return "".join(chunks)


def build_workspace_zip(root: Path) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for p in sorted(root.rglob("*")):
            if not p.is_file():
                continue
            if any(part in (".git", "node_modules", ".vibearmor", "__pycache__", ".next", "dist") for part in p.parts):
                continue
            rel = str(p.relative_to(root)).replace("\\", "/")
            zf.write(p, arcname=rel)
    return buf.getvalue()


