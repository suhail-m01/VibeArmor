"""Pillar 2 Remediator: Hardened Zero-Trust Auto-BFF Secret Relocator & Server Env Extractor.

Generates an authenticated, origin-checked, sliding-window rate-limited backend proxy route
so attackers CANNOT `curl` the generated BFF endpoint to drain API credits!
"""

from __future__ import annotations

import difflib
import re
from typing import Dict, List

from core.graph.cross_layer_graph import WorkspaceContext
from core.models import FileEdit, Finding

UPSTREAM_URLS: Dict[str, str] = {
    "openai": "https://api.openai.com/v1/chat/completions",
    "razorpay": "https://api.razorpay.com/v1/orders",
    "stripe": "https://api.stripe.com/v1/payment_intents",
    "msg91": "https://control.msg91.com/api/v5/otp",
    "generic": "https://api.provider.internal/v1/proxy",
}


def _make_diff(path: str, before: str, after: str) -> str:
    return "".join(
        difflib.unified_diff(
            before.splitlines(keepends=True),
            after.splitlines(keepends=True),
            fromfile=f"a/{path}",
            tofile=f"b/{path}",
            n=2,
        )
    )


def _env_var_name(provider: str, var_ctx: str) -> str:
    clean_ctx = re.sub(r"[^A-Za-z0-9_]", "_", var_ctx).upper().strip("_")
    clean_ctx = re.sub(r"^(NEXT_PUBLIC_|VITE_|REACT_APP_)", "", clean_ctx)
    if clean_ctx and len(clean_ctx) >= 4 and clean_ctx not in ("AUTHORIZATION", "BEARER", "HEADERS"):
        return clean_ctx
    return f"VIBEARMOR_{provider.upper()}_SECRET_KEY"


def _build_zero_trust_bff_route(provider: str, env_key: str) -> str:
    upstream = UPSTREAM_URLS.get(provider, UPSTREAM_URLS["generic"])
    return f'''// Auto-Generated by VibeArmor Zero-Trust Auto-BFF
// Enforces: (1) JWT/Supabase Caller Auth, (2) Same-Origin Lock, (3) 10 req/min Rate Limit, (4) 16KB Cap
import {{ NextRequest, NextResponse }} from "next/server";

const RATE_WINDOW_MS = 60_000;
const MAX_REQUESTS_PER_MIN = 10;
const MAX_BODY_BYTES = 16_384;
const callerBuckets = new Map<string, {{ count: number; resetAt: number }}>();

function verifyCallerSession(req: NextRequest): string | null {{
  const authHeader = req.headers.get("authorization") || req.headers.get("x-supabase-auth") || "";
  if (!authHeader.startsWith("Bearer ")) return null;
  const token = authHeader.slice(7).trim();
  return token.length >= 16 ? token.slice(0, 24) : null;
}}

function checkRateLimit(callerId: string): boolean {{
  const now = Date.now();
  const bucket = callerBuckets.get(callerId);
  if (!bucket || now > bucket.resetAt) {{
    callerBuckets.set(callerId, {{ count: 1, resetAt: now + RATE_WINDOW_MS }});
    return true;
  }}
  if (bucket.count >= MAX_REQUESTS_PER_MIN) return false;
  bucket.count += 1;
  return true;
}}

export async function POST(req: NextRequest) {{
  const origin = req.headers.get("origin");
  const host = req.headers.get("host");
  if (origin && host && !origin.includes(host)) {{
    return NextResponse.json({{ error: "VIBEARMOR_CSRF_ORIGIN_BLOCKED" }}, {{ status: 403 }});
  }}

  const callerId = verifyCallerSession(req);
  if (!callerId) {{
    return NextResponse.json({{ error: "VIBEARMOR_AUTH_SESSION_REQUIRED" }}, {{ status: 401 }});
  }}

  if (!checkRateLimit(callerId)) {{
    return NextResponse.json({{ error: "VIBEARMOR_RATE_LIMIT_EXCEEDED" }}, {{ status: 429 }});
  }}

  const rawBody = await req.text();
  if (rawBody.length > MAX_BODY_BYTES) {{
    return NextResponse.json({{ error: "VIBEARMOR_PAYLOAD_TOO_LARGE" }}, {{ status: 413 }});
  }}

  const serverSecret = process.env.{env_key};
  if (!serverSecret) {{
    return NextResponse.json({{ error: "SERVER_SECRET_NOT_CONFIGURED" }}, {{ status: 500 }});
  }}

  const upstreamRes = await fetch("{upstream}", {{
    method: "POST",
    headers: {{
      "Content-Type": "application/json",
      "Authorization": `Bearer ${{serverSecret}}`,
    }},
    body: rawBody,
  }});

  const data = await upstreamRes.json();
  return NextResponse.json(data, {{ status: upstreamRes.status }});
}}
'''


def _ensure_gitignore_dotenv(ctx: WorkspaceContext, edits: List[FileEdit]) -> None:
    gi_rel = ".gitignore"
    before_gi = ctx.file_contents.get(gi_rel, "")
    if re.search(r"(?:^|\n)\s*(?:\.env\*?|\.env\.local|\*\.env)\s*(?:\n|$|#)", before_gi):
        return
    guard_block = "# VibeArmor Pre-Push Secret Guard\n.env\n.env.*\n!.env.example\n"
    after_gi = (before_gi.rstrip() + "\n\n" + guard_block).lstrip() if before_gi.strip() else guard_block
    edits.append(
        FileEdit(
            file_path=gi_rel,
            before_content=before_gi,
            after_content=after_gi,
            unified_diff=_make_diff(gi_rel, before_gi, after_gi),
            created_new=not bool(before_gi),
        )
    )
    ctx.file_contents[gi_rel] = after_gi


def relocate_secret(finding: Finding, ctx: WorkspaceContext) -> List[FileEdit]:
    edits: List[FileEdit] = []
    rel = finding.file_path

    # Handle VA-ENV-001: Protect unignored .env* in .gitignore + create safe .env.example without touching user code!
    if finding.rule_id == "VA-ENV-001":
        _ensure_gitignore_dotenv(ctx, edits)
        env_txt = ctx.file_contents.get(rel, "")
        example_rel = ".env.example"
        before_ex = ctx.file_contents.get(example_rel, "")
        safe_lines: List[str] = []
        for raw_ln in env_txt.splitlines():
            s = raw_ln.strip()
            if not s or s.startswith("#") or "=" not in s:
                safe_lines.append(raw_ln)
            else:
                k = s.split("=", 1)[0].strip()
                safe_lines.append(f"{k}=your_{k.lower()}_here")
        after_ex = "\n".join(safe_lines).rstrip() + "\n"
        if after_ex != before_ex:
            edits.append(
                FileEdit(
                    file_path=example_rel,
                    before_content=before_ex,
                    after_content=after_ex,
                    unified_diff=_make_diff(example_rel, before_ex, after_ex),
                    created_new=not bool(before_ex),
                )
            )
            ctx.file_contents[example_rel] = after_ex
        return edits

    # Handle VA-ENV-002: Surgically strip NEXT_PUBLIC_ / VITE_ / REACT_APP_ from private key in .env!
    if finding.rule_id == "VA-ENV-002":
        before_env_file = ctx.file_contents.get(rel, "")
        bad_key = finding.metadata.get("env_key", "")
        safe_key = re.sub(r"^(?:NEXT_PUBLIC_|VITE_|REACT_APP_)", "", bad_key)
        lines = before_env_file.splitlines()
        ln_idx = finding.line_start - 1
        if 0 <= ln_idx < len(lines) and bad_key in lines[ln_idx]:
            lines[ln_idx] = lines[ln_idx].replace(bad_key, safe_key, 1)
            after_env_file = "\n".join(lines) + ("\n" if before_env_file.endswith("\n") else "")
            edits.append(
                FileEdit(
                    file_path=rel,
                    before_content=before_env_file,
                    after_content=after_env_file,
                    unified_diff=_make_diff(rel, before_env_file, after_env_file),
                )
            )
            ctx.file_contents[rel] = after_env_file
        return edits

    before = ctx.file_contents.get(rel, "")
    if not before:
        return []

    secret_val: str = finding.metadata.get("secret_value", "")
    provider: str = finding.metadata.get("provider", "generic")
    var_ctx: str = finding.metadata.get("var_context", "")
    needs_bff: bool = bool(finding.metadata.get("needs_auto_bff", False))
    env_key = _env_var_name(provider, var_ctx)

    # 1. Update .env.local & .gitignore
    env_rel = ".env.local"
    before_env = ctx.file_contents.get(env_rel, "")
    clean_secret = secret_val[7:].strip() if secret_val.lower().startswith("bearer ") else secret_val
    if f"{env_key}=" not in before_env:
        after_env = (before_env.rstrip() + f"\n{env_key}={clean_secret}\n").lstrip()
        edits.append(
            FileEdit(
                file_path=env_rel,
                before_content=before_env,
                after_content=after_env,
                unified_diff=_make_diff(env_rel, before_env, after_env),
                created_new=not bool(before_env),
            )
        )
        ctx.file_contents[env_rel] = after_env
    _ensure_gitignore_dotenv(ctx, edits)

    # 2. Client Bundle -> Full Zero-Trust Auto-BFF Transformation!
    if needs_bff:
        prefix = "frontend/src/" if rel.startswith("frontend/src/") else ("src/" if rel.startswith("src/") else "")
        bff_rel = f"{prefix}app/api/vibearmor/{provider}/route.ts"
        before_bff = ctx.file_contents.get(bff_rel, "")
        after_bff = _build_zero_trust_bff_route(provider, env_key)
        if after_bff != before_bff:
            edits.append(
                FileEdit(
                    file_path=bff_rel,
                    before_content=before_bff,
                    after_content=after_bff,
                    unified_diff=_make_diff(bff_rel, before_bff, after_bff),
                    created_new=not bool(before_bff),
                )
            )

        # Rewrite client component: remove secret variable/literal & point outbound fetch to /api/vibearmor/<provider>
        after = before
        # Replace variable declaration holding the secret with proxy endpoint reference
        after = re.sub(
            rf"(?:const|let|var)\s+[A-Za-z0-9_]+\s*=\s*['\"`]{re.escape(secret_val)}['\"`]\s*;?\n?",
            f'// VibeArmor: Secret relocated to server-only {env_key} behind Zero-Trust BFF\n',
            after,
        )
        # Replace any remaining inline literal occurrence (e.g. inside Authorization header)
        after = after.replace(f'"Bearer {clean_secret}"', '"Bearer " + (sessionToken ?? "")')
        after = after.replace(f"'Bearer {clean_secret}'", "'Bearer ' + (sessionToken ?? '')")
        after = after.replace(f"`Bearer ${{{var_ctx}}}`", "`Bearer ${sessionToken ?? ''}`")
        after = after.replace(f'"{secret_val}"', '""')
        after = after.replace(f"'{secret_val}'", "''")

        # Rewrite direct provider API URL to internal Zero-Trust BFF route
        after = re.sub(
            r"https://api\.(?:openai|razorpay|stripe)\.com/[A-Za-z0-9_/\-]+",
            f"/api/vibearmor/{provider}",
            after,
        )
        # Ensure `sessionToken` exists if referenced
        if "sessionToken" in after and "const sessionToken" not in after:
            after = after.replace(
                "// VibeArmor: Secret relocated",
                'const sessionToken = typeof window !== "undefined" ? window.localStorage.getItem("sb-access-token") : "";\n// VibeArmor: Secret relocated',
                1,
            )

        if after != before:
            edits.append(
                FileEdit(
                    file_path=rel,
                    before_content=before,
                    after_content=after,
                    unified_diff=_make_diff(rel, before, after),
                )
            )
        return edits

    # 3. Backend Python / Node Server File -> Safe Environment Variable Extraction
    after = before
    if rel.endswith(".py"):
        after = after.replace(f'"{secret_val}"', f'os.environ.get("{env_key}", "")')
        after = after.replace(f"'{secret_val}'", f'os.environ.get("{env_key}", "")')
        if "import os" not in after and after != before:
            import ast as _ast
            ins_line = 0
            try:
                _tree = _ast.parse(after)
                for _node in _tree.body:
                    if isinstance(_node, _ast.Expr) and isinstance(getattr(_node, "value", None), _ast.Constant) and isinstance(_node.value.value, str):
                        ins_line = max(ins_line, getattr(_node, "end_lineno", _node.lineno))
                    elif isinstance(_node, _ast.ImportFrom) and _node.module == "__future__":
                        ins_line = max(ins_line, getattr(_node, "end_lineno", _node.lineno))
                    else:
                        break
            except SyntaxError:
                ins_line = 0
            _lines = after.splitlines(keepends=True)
            _lines.insert(ins_line, "import os\n")
            after = "".join(_lines)
    else:
        after = after.replace(f'"{secret_val}"', f'process.env.{env_key} ?? ""')
        after = after.replace(f"'{secret_val}'", f'process.env.{env_key} ?? ""')

    if after != before:
        edits.append(
            FileEdit(
                file_path=rel,
                before_content=before,
                after_content=after,
                unified_diff=_make_diff(rel, before, after),
            )
        )
    return edits
